export const getDistrictsByState = (stateName) => {
  const foundState = COASTAL_LOCATIONS.find(
    (s) => s.state.toLowerCase() === (stateName || '').toLowerCase()
  );
  return foundState ? foundState.districts : [];
};

export const getMunicipalitiesByDistrict = (stateName, districtName) => {
  const districts = getDistrictsByState(stateName);
  const foundDistrict = districts.find(
    (d) => d.district.toLowerCase() === (districtName || '').toLowerCase()
  );
  return foundDistrict ? foundDistrict.municipalities : [];
};

export const getCoastalAreasByMunicipality = (stateName, districtName, municipalityName) => {
  const municipalities = getMunicipalitiesByDistrict(stateName, districtName);
  const foundMunicipality = municipalities.find(
    (m) => m.name.toLowerCase() === (municipalityName || '').toLowerCase()
  );
  return foundMunicipality ? foundMunicipality.coastalAreas : [];
};
